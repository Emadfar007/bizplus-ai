import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const require = createRequire(new URL('../observer/package.json', import.meta.url));
const { chromium } = require('playwright');
const origin = (process.env.VERIFY_LOGIN_ORIGIN ?? 'http://127.0.0.1:3024').replace(/\/$/, '');
const screenshots = resolve('artifacts/screenshots/manual-login');
await mkdir(screenshots, { recursive: true });
const browser = await chromium.launch({ headless: true });
const report = { origin, startedAt: new Date().toISOString(), checks: [], consoleErrors: [], session: randomUUID() };
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
await context.addInitScript(id => localStorage.setItem('bizplus.demo-session.v1', id), report.session);
const page = await context.newPage();
page.on('pageerror', error => report.consoleErrors.push(error.message));
const headers = { 'X-Demo-Session': report.session };
const api = async path => {
  const response = await context.request.get(`${origin}${path}`, { headers });
  assert.equal(response.ok(), true, `${path}: ${response.status()}`);
  return response.json();
};
const noOverflow = async () => assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false, 'Document must not overflow');
const screenshot = async name => { await noOverflow(); await page.screenshot({ path: resolve(screenshots, name), fullPage: true }); };
try {
  const config = await api('/api/login/config');
  assert.equal(config.defaultCredentials, true, 'Browser QA uses only the public synthetic demo account.');
  await page.goto(`${origin}/login`);
  await page.getByRole('heading', { name: 'Business login', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Log in', exact: true }).waitFor({ state: 'visible' });
  await page.waitForFunction(() => !document.querySelector('.login-submit')?.disabled);
  assert.equal(await page.getByRole('link', { name: 'Live tests', exact: true }).isVisible(), true, 'Main navigation must retain Live tests');
  await screenshot('login-desktop.png');
  await page.getByLabel('Username', { exact: true }).fill(config.username);
  await page.getByLabel('Password', { exact: true }).fill('incorrect-demo-password');
  await page.getByRole('button', { name: 'Log in', exact: true }).click();
  await page.getByText('Invalid username or password', { exact: true }).waitFor();
  assert.equal(await page.getByLabel('Password', { exact: true }).inputValue(), '');
  const incidentLink = page.getByRole('link', { name: /Open investigation/ });
  const incidentId = (await incidentLink.getAttribute('href')).split('/').at(-1);
  const original = await api(`/api/incidents/${incidentId}`);
  assert.equal(original.status, 'open');
  assert.equal(original.login.manualOnly, true);
  await screenshot('login-rejected.png');
  await incidentLink.click();
  await page.getByRole('heading', { name: 'Login rejected', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Enter correct credentials', exact: true }).click();
  await page.getByRole('heading', { name: 'Recover your login', exact: true }).waitFor();
  await page.getByLabel('Username', { exact: true }).fill(config.username);
  await page.getByLabel('Password', { exact: true }).fill('still-incorrect-demo-password');
  await page.getByRole('button', { name: 'Log in and verify recovery', exact: true }).click();
  await page.getByText('Invalid username or password', { exact: true }).waitFor();
  assert.equal((await api(`/api/incidents/${incidentId}`)).status, 'open');
  await screenshot('login-recovery-failed.png');
  await page.getByLabel('Password', { exact: true }).fill(config.password);
  await page.getByRole('button', { name: 'Log in and verify recovery', exact: true }).click();
  await page.getByRole('heading', { name: 'Login successful', exact: true }).waitFor();
  const recovered = await api(`/api/incidents/${incidentId}`);
  assert.equal(recovered.status, 'resolved');
  assert.equal(recovered.manualRecovery.actor, 'human');
  assert.equal((await api(`/api/runs/${original.runId}`)).status, 'failed');
  await screenshot('login-recovered.png');
  report.checks.push({ flow: 'Login -> 401 -> Investigation -> incorrect recovery -> correct manual recovery', passed: true, incidentId, originalFailurePreserved: true });
  await page.reload();
  await page.getByRole('heading', { name: 'Login successful', exact: true }).waitFor();
  report.checks.push({ flow: 'Direct recovery refresh retains verified state', passed: true });

  await page.goto(`${origin}/live-tests`);
  await page.locator('#live-test-fault').selectOption('login_401');
  await page.getByRole('button', { name: 'Open manual login test', exact: true }).click();
  await page.getByText('Login test ready.', { exact: false }).waitFor();
  await page.getByLabel('Username', { exact: true }).fill(config.username);
  await page.getByLabel('Password', { exact: true }).fill('live-test-incorrect-password');
  await page.getByRole('button', { name: 'Log in', exact: true }).click();
  await page.getByText('Invalid username or password', { exact: true }).waitFor();
  const liveId = (await page.getByRole('link', { name: /Open investigation/ }).getAttribute('href')).split('/').at(-1);
  assert.equal((await api(`/api/incidents/${liveId}`)).login.source, 'live_test');
  await screenshot('live-login-rejected.png');
  await page.getByLabel('Password', { exact: true }).fill(config.password);
  await page.getByRole('button', { name: 'Log in and verify recovery', exact: true }).click();
  await page.locator('.login-live-success').getByRole('heading', { name: 'Login successful', exact: true }).waitFor();
  assert.equal(await page.locator('.login-live-panel input').count(), 0, 'Successful live login shows a simple dashboard');
  assert.equal((await api(`/api/incidents/${liveId}`)).status, 'resolved');
  await screenshot('live-login-success.png');
  report.checks.push({ flow: 'Live tests -> username/password rejection -> Investigation incident -> correct retry -> simple dashboard', passed: true, incidentId: liveId });

  const lab = await api('/api/live/lab');
  const standalone = await context.newPage();
  await standalone.goto(lab.url);
  const form = standalone.getByTestId('manual-login-form');
  await form.waitFor();
  assert.equal(await form.locator('input').count(), 2);
  await standalone.getByLabel('Username', { exact: true }).fill(config.username);
  await standalone.getByLabel('Password', { exact: true }).fill('standalone-incorrect-password');
  await standalone.getByRole('button', { name: 'Login', exact: true }).click();
  await standalone.getByText('Invalid username or password', { exact: true }).waitFor();
  await standalone.getByLabel('Password', { exact: true }).fill(config.password);
  await standalone.getByRole('button', { name: 'Login', exact: true }).click();
  await standalone.getByText('Login successful', { exact: true }).waitFor();
  await standalone.screenshot({ path: resolve(screenshots, 'standalone-login-dashboard.png'), fullPage: true });
  report.checks.push({ flow: 'Isolated website has exactly two credential fields; rejected then manually recovered', passed: true });
  await standalone.close();

  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(`${origin}/login`);
  await page.getByRole('heading', { name: 'Business login', exact: true }).waitFor();
  await screenshot('login-mobile.png');
  await page.getByLabel('Username', { exact: true }).fill(config.username);
  await page.getByLabel('Password', { exact: true }).fill(config.password);
  await page.getByRole('button', { name: 'Log in', exact: true }).click();
  await page.getByRole('heading', { name: 'Login successful', exact: true }).waitFor();
  await screenshot('login-mobile-success.png');
  report.checks.push({ flow: '390px mobile login and success dashboard without overflow', passed: true });
  const storage = await page.evaluate(() => JSON.stringify({ local: { ...localStorage }, session: { ...sessionStorage } }));
  const incidents = await api('/api/incidents');
  for (const secret of [config.password, 'incorrect-demo-password', 'live-test-incorrect-password']) {
    assert.equal(JSON.stringify(incidents).includes(secret), false, 'Credentials must be absent from incident evidence');
    assert.equal(storage.includes(secret), false, 'Credentials must be absent from browser storage');
  }
  assert.deepEqual(report.consoleErrors, []);
  report.checks.push({ flow: 'Credential redaction, empty password after submit, no browser console errors', passed: true });
  report.completedAt = new Date().toISOString();
  await mkdir('artifacts/verification', { recursive: true });
  await writeFile('artifacts/verification/manual-login-browser.json', JSON.stringify(report, null, 2));
  console.log(JSON.stringify({ passed: report.checks.length, screenshots, report: 'artifacts/verification/manual-login-browser.json' }));
} finally { await context.close(); await browser.close(); }
