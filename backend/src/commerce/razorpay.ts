export type RazorpayTransport = (method: 'GET' | 'POST', path: string, body?: Record<string, unknown>) => Promise<unknown>;

export class CommerceError extends Error {
  constructor(readonly status: number, readonly code: string, message: string) { super(message); }
}
export class ProviderError extends CommerceError {
  constructor(message: string, readonly ambiguous: boolean) { super(502, 'RAZORPAY_UNAVAILABLE', message); }
}

export function razorpayTransport(keyId: string, keySecret: string, timeoutMs = 10_000): RazorpayTransport {
  const authorization = `Basic ${Buffer.from(`${keyId}:${keySecret}`).toString('base64')}`;
  return async (method, path, body) => {
    // Endpoint paths are generated by the integration, never supplied by a browser.
    if (!/^\/(orders(?:\/order_[A-Za-z0-9]+)?|payments\/pay_[A-Za-z0-9]+)$/.test(path)) throw new CommerceError(500, 'INVALID_PROVIDER_PATH', 'The provider request is not supported.');
    let response: Response;
    try {
      response = await fetch(`https://api.razorpay.com/v1${path}`, {
        method, headers: { Authorization: authorization, 'Content-Type': 'application/json' },
        ...(body ? { body: JSON.stringify(body) } : {}), signal: AbortSignal.timeout(timeoutMs), redirect: 'error',
      });
    } catch {
      throw new ProviderError('Razorpay could not be reached. The payment has not been verified.', true);
    }
    if (!response.ok) {
      await response.body?.cancel();
      throw new ProviderError(response.status === 401 ? 'Razorpay rejected the test credentials. Check the backend key configuration.' : 'Razorpay rejected or could not complete the request.', response.status >= 500 || response.status === 408 || response.status === 429);
    }
    try { return await response.json(); }
    catch { throw new ProviderError('Razorpay returned an unreadable response. The payment has not been verified.', true); }
  };
}
